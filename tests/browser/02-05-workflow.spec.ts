  await expect(page.locator('#living-purpose')).toHaveValue('阅读和家庭活动');
  await expect(page.locator('#living-target_width')).toHaveValue('5.2');
  await page.getByRole('button', { name: '收起需求面板' }).click();
  await page.getByRole('button', { name: /聊聊你的家/ }).click();
  const input = page.getByRole('textbox', { name: '咨询消息' });
  await input.fill('这是一条尚未发送的测试草稿');
  const keyboardBefore = await bridge(page, 'snapshot', {});
  const cameraBefore = (await bridge(page, 'inspect', {})).camera.position;
  await input.press('Delete');
  await input.press('ArrowLeft');
  expect((await bridge(page, 'snapshot', {})).scene).toEqual(keyboardBefore.scene);
  expect((await bridge(page, 'inspect', {})).camera.position).toEqual(cameraBefore);
